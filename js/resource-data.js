/* ==========================================================================
   scione.io — shared resource-index library

   v8: real static files now exist per resource (blog/{slug}.html etc.,
   generated by build.js), so this module has two consumers instead of one:

   - js/resources.js, in the browser, on the hub/listing pages (resources.
     html, blog.html, research.html, assets.html, tutorials.html) -- the
     live CSV-driven search/filter feature.
   - build.js, in Node, at build time -- reads data/resources.csv and
     content/*.md through the exact same parsing, scoring, hrefFor and
     relatedTo logic used client-side, so the generated pages and the
     live search results can never describe resources differently.

   That's why this file is wrapped UMD-style below: `require('./resource-
   data.js')` from build.js and a plain <script> tag in the browser both
   get the same object. No bundler, no transpile -- just a wrapper function.
   ========================================================================== */

(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory(); // Node (build.js)
  } else {
    root.ResourceData = factory(); // browser (<script> tag)
  }
})(typeof window !== 'undefined' ? window : globalThis, function () {
  'use strict';

  var CSV_PATH = 'data/resources.csv';

  var TYPE_LABELS = { blog: 'Blog', research: 'Research', assets: 'Assets', tutorial: 'Tutorial' };
  // Maps a CSV content_type value to the plural folder name used in the
  // pretty resources/{folder}/{slug} URL. Only "tutorial" differs (its hub
  // page/URL segment is plural "tutorials" while the CSV value stays the
  // grammatically-correct singular "tutorial").
  var TYPE_URL_FOLDER = { blog: 'blog', research: 'research', assets: 'assets', tutorial: 'tutorials' };
  var TYPE_META_LABEL = { assets: 'Free download' };
  var TYPE_GHOST_COPY = {
    blog: ['More posts on the way', "New articles get added here as they're written."],
    research: ['More questions answered soon', 'New research posts get added here as questions come up in real projects.'],
    assets: ['More downloads on the way', 'New templates and downloads get added here over time.'],
    tutorial: ['More tutorials on the way', 'New step-by-step guides get added here over time.'],
    all: ['More resources on the way', "New posts, research, downloads and tutorials get added here as they're ready."]
  };
  var TYPE_CTA = {
    blog: ["Let's connect or work with me", "Let's connect to talk shop and compare notes, or work together through Market Vantage on what you're building."],
    research: ["Let's connect or work with me", "Let's connect to talk shop and compare notes, or work together through Market Vantage on what you're building."],
    assets: ["Let's connect or work with me", "Let's connect to talk shop and compare notes, or work together through Market Vantage on what you're building."],
    tutorial: ["Let's connect or work with me", "Let's connect to talk shop and compare notes, or work together through Market Vantage on what you're building."]
  };
  // Icon paths lifted from the site's original hardcoded cards, so the
  // fallback thumb (used whenever a row has no featured_image) looks
  // identical to what was there before this went dynamic.
  var TYPE_ICON_INNER = {
    blog: '<path d="M4 19.5V6a2 2 0 0 1 2-2h9l5 5v10.5a2 2 0 0 1-2 2H6a2 2 0 0 1-2-2Z"/><polyline points="15 4 15 9 20 9"/><line x1="8" y1="13" x2="16" y2="13"/><line x1="8" y1="17" x2="13" y2="17"/>',
    research: '<circle cx="11" cy="11" r="7"/><line x1="21" y1="21" x2="16.65" y2="16.65"/>',
    assets: '<path d="M12 3v12"/><polyline points="7 10 12 15 17 10"/><line x1="4" y1="21" x2="20" y2="21"/>',
    tutorial: '<circle cx="12" cy="12" r="9"/><polygon points="10 8.5 16 12 10 15.5" fill="currentColor" stroke="none"/>'
  };

  /* ---------------------------------------------------------------------
     CSV parsing — small RFC4180-ish state machine so quoted fields
     (commas, quotes, newlines inside a cell) survive intact. Real
     spreadsheet apps (Excel, Sheets, Numbers) already export CSVs this
     way, so this just needs to read what they produce.
     --------------------------------------------------------------------- */
  function parseCSV(text) {
    var rows = [];
    var row = [];
    var field = '';
    var inQuotes = false;
    var i = 0;
    var len = text.length;

    while (i < len) {
      var char = text[i];

      if (inQuotes) {
        if (char === '"') {
          if (text[i + 1] === '"') {
            field += '"';
            i += 2;
            continue;
          }
          inQuotes = false;
          i++;
          continue;
        }
        field += char;
        i++;
        continue;
      }

      if (char === '"') {
        inQuotes = true;
        i++;
        continue;
      }
      if (char === ',') {
        row.push(field);
        field = '';
        i++;
        continue;
      }
      if (char === '\r') {
        i++;
        continue;
      }
      if (char === '\n') {
        row.push(field);
        rows.push(row);
        row = [];
        field = '';
        i++;
        continue;
      }
      field += char;
      i++;
    }
    if (field.length || row.length) {
      row.push(field);
      rows.push(row);
    }
    return rows;
  }

  function csvToObjects(text) {
    var rows = parseCSV(text).filter(function (r) {
      return r.length > 1 || (r.length === 1 && r[0].trim() !== '');
    });
    if (!rows.length) return [];
    var header = rows[0].map(function (h) { return h.trim().toLowerCase(); });
    return rows.slice(1).map(function (r) {
      var obj = {};
      header.forEach(function (key, idx) {
        obj[key] = (r[idx] === undefined ? '' : r[idx]).trim();
      });
      return obj;
    });
  }

  function loadAll() {
    var csvUrl = (typeof window !== 'undefined' && window.SiteBehavior && window.SiteBehavior.sitePath)
      ? window.SiteBehavior.sitePath(CSV_PATH)
      : CSV_PATH;
    return fetch(csvUrl)
      .then(function (res) {
        if (!res.ok) throw new Error('CSV fetch failed with status ' + res.status);
        return res.text();
      })
      .then(function (text) {
        return csvToObjects(text).filter(function (item) { return item.slug && item.title; });
      });
  }

  /* ---------------------------------------------------------------------
     Fuzzy OR search: substring match first, then a Levenshtein-distance
     fallback (scaled to word length) so close typos still hit. Query
     tokens are OR'd together and OR'd across fields (title/topic/
     excerpt/keywords) — any match counts, more/stronger matches rank
     higher. Intentionally "light," not a full search index.
     --------------------------------------------------------------------- */
  function normalize(str) {
    return String(str == null ? '' : str)
      .toLowerCase()
      .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9\s-]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  function levenshtein(a, b) {
    if (a === b) return 0;
    var al = a.length, bl = b.length;
    if (!al) return bl;
    if (!bl) return al;
    var prev = [];
    for (var j = 0; j <= bl; j++) prev[j] = j;
    for (var i = 1; i <= al; i++) {
      var cur = [i];
      for (j = 1; j <= bl; j++) {
        var cost = a.charAt(i - 1) === b.charAt(j - 1) ? 0 : 1;
        cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost);
      }
      prev = cur;
    }
    return prev[bl];
  }

  function fuzzyTolerance(word) {
    if (word.length <= 3) return 0;
    if (word.length <= 6) return 1;
    return 2;
  }

  function wordsMatch(a, b) {
    if (!a || !b) return false;
    if (a === b) return true;
    if (a.length < 2 || b.length < 2) return false;
    var tol = Math.min(fuzzyTolerance(a), fuzzyTolerance(b));
    if (tol === 0) return false;
    return levenshtein(a, b) <= tol;
  }

  var FIELD_WEIGHT = { title: 5, topic: 4, keywords: 4, excerpt: 2 };

  function scoreItem(item, tokens) {
    var title = normalize(item.title);
    var topic = normalize(item.topic);
    var excerpt = normalize(item.excerpt);
    var keywords = (item.keywords || '').split(/[|,]/).map(normalize).filter(Boolean);
    var titleWords = title.split(' ');
    var topicWords = topic.split(' ');
    var excerptWords = excerpt.split(' ');

    var total = 0;
    tokens.forEach(function (token) {
      var best = 0;
      if (title.indexOf(token) !== -1) best = Math.max(best, FIELD_WEIGHT.title);
      if (topic.indexOf(token) !== -1) best = Math.max(best, FIELD_WEIGHT.topic);
      if (excerpt.indexOf(token) !== -1) best = Math.max(best, FIELD_WEIGHT.excerpt);
      if (keywords.some(function (k) { return k.indexOf(token) !== -1; })) best = Math.max(best, FIELD_WEIGHT.keywords);

      if (best === 0) {
        if (titleWords.some(function (w) { return wordsMatch(w, token); })) best = Math.max(best, FIELD_WEIGHT.title * 0.7);
        if (topicWords.some(function (w) { return wordsMatch(w, token); })) best = Math.max(best, FIELD_WEIGHT.topic * 0.7);
        if (excerptWords.some(function (w) { return wordsMatch(w, token); })) best = Math.max(best, FIELD_WEIGHT.excerpt * 0.7);
        if (keywords.some(function (k) { return wordsMatch(k, token); })) best = Math.max(best, FIELD_WEIGHT.keywords * 0.7);
      }
      total += best;
    });
    return total;
  }

  function search(items, query) {
    var tokens = normalize(query).split(' ').filter(Boolean);
    if (!tokens.length) {
      return items.slice().sort(function (a, b) { return (b.publish_date || '').localeCompare(a.publish_date || ''); });
    }
    return items
      .map(function (item) { return { item: item, score: scoreItem(item, tokens) }; })
      .filter(function (r) { return r.score > 0; })
      .sort(function (a, b) { return b.score - a.score || (b.item.publish_date || '').localeCompare(a.item.publish_date || ''); })
      .map(function (r) { return r.item; });
  }

  /* ---------------------------------------------------------------------
     Rendering helpers
     --------------------------------------------------------------------- */
  function escapeHTML(str) {
    return String(str == null ? '' : str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');
  }
  function escapeAttr(str) {
    return escapeHTML(str).replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  function formatDate(iso) {
    if (!iso) return '';
    var parts = iso.split('-');
    if (parts.length !== 3) return iso;
    var y = Number(parts[0]), m = Number(parts[1]), d = Number(parts[2]);
    if (!y || !m || !d) return iso;
    var dt = new Date(Date.UTC(y, m - 1, d));
    if (isNaN(dt.getTime())) return iso;
    return dt.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' });
  }

  // The real, permanent URL for an item -- e.g. blog/why-startup-websites-
  // fail-90-days.html -- a genuine static file build.js generates, not a
  // routing trick. fromDepth is how many folders deep the *calling* page
  // already is relative to the site root: 0 (default) for the hub pages,
  // which live at the root; 1 when build.js links between two generated
  // pages, since those live one folder down (blog/, research/, assets/,
  // tutorials/) and need a "../" to get back up before going into the
  // target's own folder.
  function hrefFor(item, fromDepth) {
    var folder = TYPE_URL_FOLDER[item.content_type] || item.content_type;
    var prefix = fromDepth ? new Array(fromDepth + 1).join('../') : '';
    return prefix + folder + '/' + encodeURIComponent(item.slug) + '.html';
  }

  function iconSVG(contentType) {
    var inner = TYPE_ICON_INNER[contentType] || TYPE_ICON_INNER.blog;
    return '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">' + inner + '</svg>';
  }

  function thumbHTML(item, fromDepth) {
    if (item.featured_image) {
      var isAbsolute = /^(https?:)?\/\//i.test(item.featured_image);
      var prefix = (!isAbsolute && fromDepth) ? new Array(fromDepth + 1).join('../') : '';
      return '<img src="' + escapeAttr(prefix + item.featured_image) + '" alt="" loading="lazy">';
    }
    return iconSVG(item.content_type);
  }

  function cardHTML(item, featured, fromDepth) {
    var typeLabel = TYPE_LABELS[item.content_type] || item.content_type;
    var metaLabel = TYPE_META_LABEL[item.content_type] || 'Brent Scione';
    var dateLabel = formatDate(item.publish_date);
    return (
      '<a href="' + escapeAttr(hrefFor(item, fromDepth)) + '" class="post-card' + (featured ? ' post-card--featured' : '') + '">' +
        '<div class="post-thumb">' + thumbHTML(item, fromDepth) + '</div>' +
        '<div class="post-body">' +
          '<span class="tag">' + escapeHTML(typeLabel) + '</span>' +
          '<h3>' + escapeHTML(item.title) + '</h3>' +
          '<p>' + escapeHTML(item.excerpt) + '</p>' +
          '<div class="post-meta"><span>' + escapeHTML(metaLabel) + '</span><span class="dot-sep"></span><span>' + escapeHTML(dateLabel) + '</span></div>' +
        '</div>' +
      '</a>'
    );
  }

  function ghostCardHTML(scopeType) {
    var copy = TYPE_GHOST_COPY[scopeType] || TYPE_GHOST_COPY.all;
    return (
      '<div class="post-card post-card--ghost">' +
        '<div class="post-thumb">' + iconSVG(scopeType) + '</div>' +
        '<div class="post-body">' +
          '<span class="tag tag--muted">Coming soon</span>' +
          '<h3>' + escapeHTML(copy[0]) + '</h3>' +
          '<p>' + escapeHTML(copy[1]) + '</p>' +
        '</div>' +
      '</div>'
    );
  }

  function relatedTo(items, current, count) {
    var pool = items.filter(function (i) { return i.slug !== current.slug; });
    var sameTopic = pool.filter(function (i) { return i.topic && i.topic === current.topic; });
    var rest = pool.filter(function (i) { return !(i.topic && i.topic === current.topic); });
    var byDate = function (a, b) { return (b.publish_date || '').localeCompare(a.publish_date || ''); };
    return sameTopic.sort(byDate).concat(rest.sort(byDate)).slice(0, count || 3);
  }

  return {
    CSV_PATH: CSV_PATH,
    TYPE_LABELS: TYPE_LABELS,
    TYPE_URL_FOLDER: TYPE_URL_FOLDER,
    TYPE_META_LABEL: TYPE_META_LABEL,
    TYPE_GHOST_COPY: TYPE_GHOST_COPY,
    TYPE_CTA: TYPE_CTA,
    parseCSV: parseCSV,
    csvToObjects: csvToObjects,
    loadAll: loadAll,
    normalize: normalize,
    levenshtein: levenshtein,
    wordsMatch: wordsMatch,
    scoreItem: scoreItem,
    search: search,
    escapeHTML: escapeHTML,
    escapeAttr: escapeAttr,
    formatDate: formatDate,
    hrefFor: hrefFor,
    iconSVG: iconSVG,
    thumbHTML: thumbHTML,
    cardHTML: cardHTML,
    ghostCardHTML: ghostCardHTML,
    relatedTo: relatedTo
  };
});
